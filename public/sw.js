/*
 * Minimal same-origin service worker for the curriculum shell.
 * It deliberately avoids API responses, credentials, and third-party content.
 */
const CACHE_NAME = 'sectrilha-shell-v2';
const APP_SHELL_URL = '/';

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.add(APP_SHELL_URL))
      // A failed precache must not prevent a later online installation.
      .catch(() => undefined)
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((key) => key.startsWith('sectrilha-shell-') && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      ))
      .then(() => self.clients.claim())
  );
});

function isSameOriginGetRequest(request) {
  if (request.method !== 'GET') return false;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return false;
  if (url.pathname.startsWith('/api/') || url.searchParams.has('_rsc') || request.headers.get('RSC')) return false;
  // Avoid cache-only requests generated by browser internals.
  if (request.cache === 'only-if-cached' && request.mode !== 'same-origin') return false;

  return true;
}

async function cacheResponse(request, response) {
  if (!response || !response.ok || response.type === 'opaque') return response;

  const cache = await caches.open(CACHE_NAME);
  await cache.put(request, response.clone());
  return response;
}

async function networkFirst(request) {
  try {
    return await cacheResponse(request, await fetch(request));
  } catch {
    const cached = await caches.match(request);
    return cached || await caches.match(APP_SHELL_URL) || Response.error();
  }
}

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  try {
    return await cacheResponse(request, await fetch(request));
  } catch {
    return Response.error();
  }
}

self.addEventListener('fetch', (event) => {
  if (!isSameOriginGetRequest(event.request)) return;

  if (event.request.mode === 'navigate') {
    event.respondWith(networkFirst(event.request));
    return;
  }

  const url = new URL(event.request.url);
  // Only immutable Next build assets use cache-first. RSC payloads, route
  // transitions and development chunks always go to the network first.
  if (url.pathname.startsWith('/_next/static/')) event.respondWith(cacheFirst(event.request));
});
